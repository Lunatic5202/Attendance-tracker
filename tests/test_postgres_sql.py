"""PostgreSQL compatibility tests.

The runtime tests need no database server: every statement the app issues is
translated to its PostgreSQL form and parsed with the real PostgreSQL parser
from ``pglast``. Install it with ``pip install pglast`` to enable them; without
it those tests are skipped and the rest of the suite still runs.
"""

