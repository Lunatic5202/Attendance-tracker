class FakeCursor:
    def __init__(self, conn):
        self._conn = conn
        self._rows = []

    def execute(self, sql, params=()):
        self._conn.executed.append((sql, params))
        self._rows = self._conn.rows

    def fetchone(self):
        return self._rows[0] if self._rows else None

    def fetchall(self):
        return list(self._rows)


class FakeRawConnection:
    def __init__(self, rows=()):
        self.executed = []
        self.rows = list(rows)
        self.commits = 0
        self.rollbacks = 0
        self.closed = False

    def cursor(self, row_factory=None):
        return FakeCursor(self)

    def commit(self):
        self.commits += 1

    def rollback(self):
        self.rollbacks += 1

    def close(self):
        self.closed = True


class FakePool:
    def __init__(self):
        self.returned = []
        self.opened = 0

    def getconn(self):
        self.opened += 1
        return FakeRawConnection(rows=[{"id": "EMP001"}])

    def putconn(self, conn):
        self.returned.append(conn)


class PostgresConnectionTests(unittest.TestCase):
    def test_execute_translates_placeholders_and_passes_params(self):
        raw = FakeRawConnection()
        conn = db.PostgresConnection(raw)
        conn.execute("SELECT * FROM employees WHERE id = ?", ("EMP001",))
        sql, params = raw.executed[0]
        self.assertEqual(sql, "SELECT * FROM employees WHERE id = %s")
        self.assertEqual(params, ("EMP001",))

    def test_execute_defaults_to_empty_params(self):
        raw = FakeRawConnection()
        db.PostgresConnection(raw).execute("SELECT 1")
        self.assertEqual(raw.executed[0][1], ())

    def test_fetchone_returns_mapping(self):
        raw = FakeRawConnection(rows=[{"id": "EMP001"}])
        row = db.PostgresConnection(raw).execute("SELECT id FROM employees").fetchone()
        self.assertEqual(row["id"], "EMP001")

    def test_fetchall_returns_empty_list(self):
        raw = FakeRawConnection(rows=[])
        self.assertEqual(db.PostgresConnection(raw).execute("SELECT id FROM employees").fetchall(), [])

    def test_context_manager_commits_on_success(self):
        raw = FakeRawConnection()
        with db.PostgresConnection(raw) as conn:
            conn.execute("SELECT 1")
        self.assertEqual(raw.commits, 1)
        self.assertEqual(raw.rollbacks, 0)
        self.assertTrue(raw.closed)

    def test_context_manager_rolls_back_on_error(self):
        raw = FakeRawConnection()
        with self.assertRaises(ValueError):
            with db.PostgresConnection(raw) as conn:
                conn.execute("SELECT 1")
                raise ValueError("boom")
        self.assertEqual(raw.rollbacks, 1)
        self.assertEqual(raw.commits, 0)
        self.assertTrue(raw.closed)

    def test_close_returns_connection_to_pool(self):
        pool = FakePool()
        conn = db.PostgresConnection(pool.getconn(), pool)
        conn.close()
        self.assertEqual(len(pool.returned), 1)

    def test_context_manager_returns_connection_to_pool(self):
        pool = FakePool()
        raw = pool.getconn()
        with db.PostgresConnection(raw, pool):
            pass
        self.assertEqual(pool.returned, [raw])


class BackendSelectionTests(unittest.TestCase):
    def test_sqlite_is_default_without_database_url(self):
        with patch.object(db, "DATABASE_URL", ""):
            self.assertFalse(db.using_postgres())

    def test_postgres_url_selects_postgres(self):
        for url in ("postgres://u:p@h:5432/d", "postgresql://u:p@h:5432/d"):
            with patch.object(db, "DATABASE_URL", url):
                self.assertTrue(db.using_postgres(), url)

    def test_non_postgres_url_falls_back_to_sqlite(self):
        with patch.object(db, "DATABASE_URL", "mysql://u:p@h/d"):
            self.assertFalse(db.using_postgres())


